import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=readFileSync('public/activetournament/script.js','utf8').split('// MODAL FUNCTIONS.')[0];
const context=vm.createContext({Intl,Date,document:{getElementById:()=>({options:[{value:'auto'}]})}});
vm.runInContext(source,context);
const run=code=>vm.runInContext(code,context);
assert.equal(run("dateKey(monthDays(civilDate(2026,8,1))[0])"),'2026-08-30');
assert.equal(run("monthDays(civilDate(2026,8,1)).length"),35);
assert.equal(run("monthDays(civilDate(2028,1,1)).filter(d=>d.getUTCMonth()===1).length"),29);
assert.equal(run("monthDays(civilDate(2100,1,1)).filter(d=>d.getUTCMonth()===1).length"),28);
assert.equal(run("instantDay('2026-09-20T00:00:00Z','America/New_York')"),'2026-09-19');
assert.equal(run("instantDay('2026-09-20T00:00:00Z','Asia/Tokyo')"),'2026-09-20');
assert.equal(run("calendarState.timezone='America/Los_Angeles';displayTime('2026-09-20T00:00:00Z')"),'5:00 PM');
assert.equal(run("calendarState.timezone='America/New_York';displayTime('2026-01-20T00:00:00Z')"),'7:00 PM');
assert.equal(run("displayTime('2026-09-20T00:00:00Z')"),'8:00 PM');
assert.equal(run("eventsOn('2026-09-19').some(e=>e.id==='open-bracket')"),true);
assert.equal(run("calendarState.timezone='Asia/Tokyo';eventsOn('2026-09-19').some(e=>e.id==='open-bracket')"),false);
assert.equal(run("eventsOn('2026-09-20').some(e=>e.id==='open-bracket')"),true);
assert.equal(run("calendarState.timezone='UTC';eventsOn('2026-09-12').some(e=>e.id==='gunfight')"),true);
assert.equal(run("holidaysForYear(2026).find(h=>h.title==='Memorial Day').date"),'2026-05-25');
assert.equal(run("holidaysForYear(2026).find(h=>h.title==='Thanksgiving').date"),'2026-11-26');
assert.equal(run("holidaysForYear(2027).find(h=>h.title==='Labor Day').date"),'2027-09-06');
console.log('16 checks passed: Gregorian alignment, leap years, DST, international day shifts, multi-day overlap and holiday rules.');
